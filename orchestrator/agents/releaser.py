"""Releaser agent: opens a real GitHub Pull Request and notifies humans.

The Releaser is the final agent in the pipeline. After the Verifier
returns ``verdict=verified`` the state machine hands the incident off
here. The Releaser:

1. Composes a PR title, PR body, Slack message, and commit message via
   one LLM round-trip (cheap model — the diff itself is already
   produced).
2. Creates a branch off ``main`` named ``autosre/inc-<short_id>``
   (idempotent: re-runs land on the existing branch).
3. Applies the Fix Author's unified diff *in memory* to the file
   contents read from GitHub, then commits the resulting blob via
   ``repo.update_file`` on the branch.
4. Opens a Pull Request from the branch into ``main`` (or returns the
   existing PR's URL if one is already open against this branch).
5. POSTs a Slack notification to the configured webhook (skipped if
   none configured — the release still succeeds).

Every step opens a child span so the trace tree captures the failure
mode if anything goes wrong, and the LLM call is the only thing that
isn't deterministic — the GitHub mutations and Slack post are pure
side effects against the injected tools.
"""

from __future__ import annotations

import json
import logging
import re
from typing import Any, Optional, TYPE_CHECKING

import httpx  # noqa: F401 — kept so tests can patch releaser.httpx.AsyncClient

from orchestrator.agents.base import BaseAgent
from orchestrator.timeutil import utcnow
from orchestrator.tools.patch_tool import PatchApplyError, apply_unified_diff
from orchestrator.tools.slack_tool import SlackNotifier


if TYPE_CHECKING:  # pragma: no cover — typing only
    from sqlmodel import Session

    from orchestrator.models import Incident
    from orchestrator.tools.github_tool import GitHubTool
    from orchestrator.tracing import SpanContext


log = logging.getLogger("orchestrator.agents.releaser")


_PR_URL_PLACEHOLDER = "{{PR_URL}}"
_SLACK_TIMEOUT_S = 5.0
_BRANCH_PREFIX = "autosre/inc-"
_VICTIM_PATH_PREFIX_RE = re.compile(r"^victim_app/")


def _short_incident_id(incident_id: str) -> str:
    """Strip the ``inc_`` prefix and clamp to 12 chars for a branch slug."""
    body = incident_id
    if body.startswith("inc_"):
        body = body[len("inc_") :]
    return body[:12] or "unknown"


def _normalize_repo_path(path: Optional[str]) -> str:
    """Strip a leading ``victim_app/`` so paths target the repo root.

    The Fix Author intentionally re-roots paths under ``victim_app/``
    so its diff applies to the verifier sandbox (which copies
    ``victim_app/`` as the git root). For the Releaser, we're working
    against the real repo, where the suspect file usually lives at the
    repo root. We strip the prefix if present; the GitHubTool's
    path-resolver will still find the file at whatever depth it lives.
    """
    if not path:
        return "app.py"
    p = path.replace("\\", "/").lstrip("./")
    p = _VICTIM_PATH_PREFIX_RE.sub("", p)
    return p or "app.py"


class ReleaserAgent(BaseAgent):
    """Opens a real PR and posts a Slack notification for a verified fix."""

    name = "releaser"
    # Cheap model — this is purely prose composition.
    model = "gpt-4o-mini"

    SYSTEM_PROMPT = """You are an SRE Releaser composing a Pull Request description and Slack incident notification for an autonomously-resolved production bug.

Given the incident context and the proposed fix, produce:
1. A PR title (max 72 chars, conventional commit style: 'fix: ...' or 'hotfix: ...')
2. A PR body in markdown with sections: Incident, Root Cause, Fix, Verification, Risk Assessment
3. A Slack message in markdown (short, scannable, with the incident ID + classification + risk + PR link placeholder {{PR_URL}})

The PR body must include this footer EXACTLY:

---
🤖 *Autonomously generated by the SRE Incident Response System*
Incident ID: `{incident_id}` | Workflow: `{workflow_id}` | Risk: `{risk}` | Confidence: `{confidence}`

Respond with ONLY this JSON:
{
  "pr_title": "...",
  "pr_body": "...",
  "slack_message": "...",
  "commit_message": "fix: <one-line summary>"
}"""

    def __init__(
        self,
        openai_client: Any,
        tracer: Any,
        github_tool: "GitHubTool",
        slack_webhook_url: Optional[str] = None,
    ) -> None:
        super().__init__(openai_client, tracer)
        self.github = github_tool
        self.slack_webhook_url = (slack_webhook_url or "").strip() or None

    # ------------------------------------------------------------------
    # Run
    # ------------------------------------------------------------------

    async def run(
        self,
        *,
        incident: "Incident",
        span: "SpanContext",
        session: "Session",
    ) -> dict:
        # Preconditions: a non-empty diff + a known suspect file. If
        # either is missing the state machine shouldn't have called us,
        # but we fail loudly rather than producing a malformed PR.
        diff = incident.proposed_patch or ""
        if not diff.strip():
            raise RuntimeError("Releaser: incident.proposed_patch is empty")

        suspect_file_raw = incident.suspect_file or "app.py"
        target_path = _normalize_repo_path(suspect_file_raw)
        branch_name = f"{_BRANCH_PREFIX}{_short_incident_id(incident.id)}"

        span.event(
            "release_started",
            {
                "incident_id": incident.id,
                "target_path": target_path,
                "branch": branch_name,
                "slack_enabled": self.slack_webhook_url is not None,
            },
        )

        # --------------------------------------------------------------
        # Step 1: Compose PR + Slack text via LLM
        # --------------------------------------------------------------
        composed = await self._compose(incident=incident, span=span)
        pr_title = composed["pr_title"]
        pr_body = composed["pr_body"]
        slack_template = composed["slack_message"]
        commit_message = composed["commit_message"]

        # --------------------------------------------------------------
        # Step 2: Create the branch (idempotent)
        # --------------------------------------------------------------
        with span.child_span(
            "releaser.create_branch",
            metadata={"branch": branch_name, "base": "main"},
        ) as branch_span:
            branch_info = await self.github.ensure_branch(
                branch_name, base="main", span=branch_span
            )
            branch_span.event(
                "branch_ready",
                {
                    "created": branch_info.get("created", False),
                    "branch": branch_name,
                },
            )

        # --------------------------------------------------------------
        # Step 3: Apply the patch in memory and commit to the branch
        # --------------------------------------------------------------
        with span.child_span(
            "releaser.apply_patch",
            metadata={"target_path": target_path},
        ) as patch_span:
            # Re-read the file from GitHub right now — not from any
            # cached / Verifier-sandbox copy. The Verifier's sandbox was
            # a snapshot taken minutes ago and a maintainer may have
            # pushed a whitespace-only edit since. ``get_file_with_sha``
            # gives us both the live content AND the sha we need for
            # the subsequent ``update_file_on_branch`` call.
            patch_span.event(
                "fetching_target_file",
                {"path": target_path, "ref": "main"},
            )
            file_info = await self.github.get_file_with_sha(
                target_path, ref="main", span=patch_span
            )
            resolved_path = file_info["path"]
            original_content = file_info["content"]
            base_sha = file_info["sha"]
            if not original_content:
                raise RuntimeError(
                    f"Releaser cannot read {resolved_path} from main branch "
                    f"(GitHub returned empty content)"
                )
            patch_span.event(
                "source_loaded",
                {
                    "resolved_path": resolved_path,
                    "chars": len(original_content),
                    "sha": base_sha[:10],
                },
            )

            patch_span.event(
                "applying_patch",
                {
                    "target_chars": len(original_content),
                    "patch_chars": len(diff),
                },
            )
            try:
                new_content = apply_unified_diff(original_content, diff)
                patch_span.event(
                    "patch_applied",
                    {"strict_or_fuzzy": "succeeded"},
                )
            except PatchApplyError as exc:
                # Make the failure debuggable directly from Omium /
                # local traces — without these snippets the operator
                # has to manually fetch the file from main and compare
                # against the diff to see where the drift is.
                snippet_lines = original_content.splitlines()
                suspect_line = incident.suspect_line or 1
                window_start = max(0, suspect_line - 5)
                window_end = min(len(snippet_lines), suspect_line + 5)
                target_snippet = "\n".join(
                    snippet_lines[window_start:window_end]
                )
                diff_snippet = "\n".join(diff.splitlines()[:20])
                patch_span.event(
                    "patch_apply_failed",
                    {
                        "error": str(exc)[:500],
                        "target_snippet": target_snippet[:2000],
                        "diff_snippet": diff_snippet[:2000],
                        "suspect_line": suspect_line,
                        "window": f"{window_start + 1}-{window_end}",
                    },
                )
                raise

            if new_content == original_content:
                # The diff produced no actual change — almost certainly
                # a bug in the diff (or it was already merged). Don't
                # open an empty PR.
                raise PatchApplyError(
                    "patch produced no changes; aborting release to avoid empty PR"
                )

            # The branch may already have a different blob sha (if this
            # is a retry on the same branch). Try the update with the
            # base sha first; if GitHub rejects with 409/422, re-read
            # the file *on the branch* and retry once.
            try:
                commit_result = await self.github.update_file_on_branch(
                    path=resolved_path,
                    message=commit_message,
                    content=new_content,
                    sha=base_sha,
                    branch=branch_name,
                    span=patch_span,
                )
            except Exception as first_exc:  # noqa: BLE001
                patch_span.event(
                    "update_file_retry",
                    {"first_error": str(first_exc)[:300]},
                )
                # Re-read on the branch and retry with that sha.
                try:
                    branch_file = await self.github.get_file_with_sha(
                        resolved_path, ref=branch_name, span=patch_span
                    )
                except Exception:
                    raise first_exc
                if branch_file["content"] == new_content:
                    # Already up-to-date on the branch — nothing more
                    # to commit. Treat as success.
                    commit_result = {"commit_sha": None, "skipped": True}
                else:
                    commit_result = await self.github.update_file_on_branch(
                        path=resolved_path,
                        message=commit_message,
                        content=new_content,
                        sha=branch_file["sha"],
                        branch=branch_name,
                        span=patch_span,
                    )
            patch_span.event(
                "patch_committed",
                {
                    "branch": branch_name,
                    "commit_sha": (commit_result.get("commit_sha") or "")[:10],
                    "skipped": commit_result.get("skipped", False),
                },
            )

        # --------------------------------------------------------------
        # Step 4: Open the PR (or return the existing one)
        # --------------------------------------------------------------
        with span.child_span(
            "releaser.open_pr",
            metadata={"branch": branch_name, "base": "main"},
        ) as pr_span:
            existing = await self.github.find_pr_by_head(
                branch_name, span=pr_span
            )
            if existing:
                pr_info = existing
                pr_span.event(
                    "pr_already_open",
                    {"number": pr_info.get("number"), "url": pr_info.get("url")},
                )
            else:
                pr_info = await self.github.create_pull(
                    title=pr_title,
                    body=pr_body,
                    head=branch_name,
                    base="main",
                    span=pr_span,
                )
                pr_span.event(
                    "pr_opened",
                    {"number": pr_info.get("number"), "url": pr_info.get("url")},
                )

        pr_url = pr_info.get("url") or ""
        pr_number = pr_info.get("number")

        # --------------------------------------------------------------
        # Step 5: Substitute the PR URL into the Slack message
        # --------------------------------------------------------------
        slack_message = slack_template.replace(_PR_URL_PLACEHOLDER, pr_url)

        # --------------------------------------------------------------
        # Step 6: Post to Slack (best-effort)
        # --------------------------------------------------------------
        slack_posted: Optional[bool]
        if self.slack_webhook_url:
            slack_posted = await self._post_slack(slack_message, span=span)
        else:
            with span.child_span(
                "releaser.notify_slack",
                metadata={"webhook": "disabled"},
            ) as slack_span:
                slack_span.event(
                    "slack_disabled",
                    {"reason": "no SLACK_WEBHOOK_URL configured"},
                )
                log.info(
                    "Slack disabled — would have posted: %s",
                    slack_message[:200],
                )
            slack_posted = False

        # --------------------------------------------------------------
        # Step 7: Persist results onto the incident
        # --------------------------------------------------------------
        incident.pr_url = pr_url
        incident.pr_number = int(pr_number) if pr_number is not None else None
        incident.pr_branch = branch_name
        incident.slack_posted = bool(slack_posted)
        incident.updated_at = utcnow()
        session.add(incident)
        session.commit()
        session.refresh(incident)

        span.event(
            "release_complete",
            {
                "pr_url": pr_url,
                "pr_number": pr_number,
                "branch": branch_name,
                "slack_posted": slack_posted,
            },
        )

        return {
            "pr_url": pr_url,
            "pr_number": pr_number,
            "pr_branch": branch_name,
            "slack_posted": bool(slack_posted),
            "slack_message": slack_message,
            "commit_message": commit_message,
        }

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    async def _compose(
        self,
        *,
        incident: "Incident",
        span: "SpanContext",
    ) -> dict:
        """One LLM call → ``{"pr_title", "pr_body", "slack_message", "commit_message"}``.

        We feed the model the incident scalars + the full proposed diff
        so it can reference specific changed lines in the Risk
        Assessment section.
        """
        with span.child_span(
            "releaser.compose",
            metadata={"model": self.model},
        ) as compose_span:
            user_prompt = self._build_compose_prompt(incident)
            raw = await self._call_llm(
                system=self.SYSTEM_PROMPT,
                user=user_prompt,
                span=compose_span,
                response_format={"type": "json_object"},
            )
            parsed = _parse_compose_payload(raw, incident)
            compose_span.event(
                "compose_complete",
                {
                    "title_chars": len(parsed["pr_title"]),
                    "body_chars": len(parsed["pr_body"]),
                    "slack_chars": len(parsed["slack_message"]),
                },
            )
            return parsed

    def _build_compose_prompt(self, incident: "Incident") -> str:
        verification_summary = "(none recorded)"
        if incident.verification_result:
            try:
                parsed = json.loads(incident.verification_result)
                verification_summary = (
                    f"verdict={parsed.get('verdict')}, "
                    f"tests_passed={parsed.get('tests_passed')}, "
                    f"duration={parsed.get('duration_seconds')}s"
                )
            except Exception:
                verification_summary = incident.verification_result[:300]

        confidence = (
            f"{incident.fix_confidence:.2f}"
            if isinstance(incident.fix_confidence, (int, float))
            else "n/a"
        )

        diff_excerpt = (incident.proposed_patch or "")[:4000]

        return (
            "INCIDENT REPORT\n"
            f"Incident ID: {incident.id}\n"
            f"Workflow ID: {incident.workflow_id or '(none)'}\n"
            f"Service: {incident.source_service}\n"
            f"Endpoint: {incident.endpoint}\n"
            f"Exception: {incident.exception_class}: {incident.exception_message}\n"
            f"Classification: {incident.classification or 'unknown'} "
            f"(severity {incident.severity or '?'})\n\n"
            f"ROOT CAUSE\n{incident.root_cause or '(none recorded)'}\n\n"
            f"FIX EXPLANATION\n{incident.fix_explanation or '(none recorded)'}\n"
            f"Risk: {incident.fix_risk_level or 'medium'}\n"
            f"Confidence: {confidence}\n\n"
            f"VERIFICATION\n{verification_summary}\n\n"
            "PROPOSED DIFF (already verified clean in sandbox):\n"
            f"{diff_excerpt}\n\n"
            "Compose the PR title, PR body, Slack message, and commit message. "
            "Use {{PR_URL}} as the placeholder for the pull-request link in the "
            "Slack message — the orchestrator will substitute it after the PR "
            "is opened. The PR body footer is mandatory; include the literal "
            f"`{incident.id}` as Incident ID and the literal "
            f"`{incident.workflow_id or 'n/a'}` as Workflow."
        )

    async def _post_slack(
        self, message: str, span: "SpanContext"
    ) -> bool:
        """POST the message to the Slack webhook. Returns True on 2xx."""
        with span.child_span(
            "releaser.notify_slack",
            metadata={"webhook": "configured", "chars": len(message)},
        ) as slack_span:
            notifier = SlackNotifier(self.slack_webhook_url, timeout_s=_SLACK_TIMEOUT_S)
            result = await notifier.post(message)
            slack_span.event(
                "slack_posted" if result.ok else "slack_post_failed",
                result.as_event(),
            )
            return result.ok


# ---------------------------------------------------------------------------
# Parsing helpers (module-level so tests can exercise them directly)
# ---------------------------------------------------------------------------

_JSON_FENCE_RE = re.compile(r"```(?:json)?\s*(.*?)```", re.DOTALL)


def _strip_fences(raw: str) -> str:
    """Strip ```json ... ``` fences if the model emits them."""
    if not raw:
        return ""
    candidate = raw.strip()
    m = _JSON_FENCE_RE.search(candidate)
    if m:
        candidate = m.group(1).strip()
    return candidate


def _parse_compose_payload(raw: str, incident: "Incident") -> dict:
    """Parse the LLM JSON response, filling in safe defaults for missing fields."""
    cleaned = _strip_fences(raw)
    try:
        parsed = json.loads(cleaned) if cleaned else {}
    except Exception as exc:
        raise RuntimeError(f"Releaser compose returned invalid JSON: {exc}") from exc
    if not isinstance(parsed, dict):
        raise RuntimeError(
            f"Releaser compose JSON was not an object (got {type(parsed).__name__})"
        )

    def _str_or(default: str, key: str) -> str:
        v = parsed.get(key)
        if isinstance(v, str) and v.strip():
            return v.strip()
        return default

    classification = incident.classification or "unknown"
    risk = incident.fix_risk_level or "medium"
    short_summary = (incident.fix_explanation or "Autonomous SRE hotfix").splitlines()[0][:60]

    pr_title = _str_or(
        f"fix: autonomous hotfix for {classification} on {incident.endpoint}",
        "pr_title",
    )
    if len(pr_title) > 72:
        pr_title = pr_title[:69] + "..."

    pr_body = _str_or(
        (
            f"## Incident\n\n`{incident.id}` — {incident.exception_class}: "
            f"{incident.exception_message}\n\n"
            f"## Root Cause\n\n{incident.root_cause or '(see investigation)'}\n\n"
            f"## Fix\n\n{incident.fix_explanation or short_summary}\n\n"
            f"## Verification\n\nVerifier passed tests in sandbox.\n\n"
            f"## Risk Assessment\n\nRisk level: {risk}\n\n"
            f"---\n"
            f"🤖 *Autonomously generated by the SRE Incident Response System*\n"
            f"Incident ID: `{incident.id}` | "
            f"Workflow: `{incident.workflow_id or 'n/a'}` | "
            f"Risk: `{risk}` | "
            f"Confidence: `{incident.fix_confidence or 0.0:.2f}`"
        ),
        "pr_body",
    )

    slack_message = _str_or(
        (
            ":rotating_light: *Autonomous SRE Fix Deployed*\n"
            f"*Incident:* `{incident.id}` | *Class:* `{classification}` | *Risk:* `{risk}`\n"
            f"*Summary:* {short_summary}\n"
            f"*PR:* {_PR_URL_PLACEHOLDER}"
        ),
        "slack_message",
    )

    commit_message = _str_or(
        f"fix: {short_summary}",
        "commit_message",
    )
    # Conventional-commit clamp: keep the first line under 72 chars.
    first_line = commit_message.splitlines()[0]
    if len(first_line) > 72:
        rest = "\n".join(commit_message.splitlines()[1:])
        commit_message = first_line[:72] + (f"\n{rest}" if rest else "")

    return {
        "pr_title": pr_title,
        "pr_body": pr_body,
        "slack_message": slack_message,
        "commit_message": commit_message,
    }


